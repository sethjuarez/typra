export const JAVA_EDITABLE_SEAM_MARKER = `// ${EDITABLE_SEAM_MARKER}`;
export const JAVA_EDITABLE_SEAM_NOTE = "// Typra editable seam. This file is created once and is safe to edit.";

/**
 * Adds the editable-seam marker to a pre-existing helper that predates the marker contract.
 * Returns null when the file already carries the marker and needs no migration.
 *
 * Seam files are create-once and consumer-owned, so migration only prepends the comment
 * header; hand-written bodies are never rewritten. A leading BOM stays at byte zero and the
 * file's dominant line ending is preserved so the result stays valid and diff-clean.
 */
export function ensureJavaEditableSeamMarker(existingSource: string): string | null {
  if (hasEditableSeamMarker(existingSource)) return null;

  const bom = existingSource.startsWith("\uFEFF") ? "\uFEFF" : "";
  const body = bom ? existingSource.slice(1) : existingSource;
  const eol = /\r\n/.test(body) ? "\r\n" : "\n";
  return `${bom}${JAVA_EDITABLE_SEAM_MARKER}${eol}${JAVA_EDITABLE_SEAM_NOTE}${eol}${body}`;
}

export function emitJavaMethodHelper(type: TypeDecl, packageName: string): { filename: string; source: string } | null {
  if (type.isProtocol || type.methods.length === 0) return null;
  const typeName = javaTypeName(type.typeName.name);
  const helperName = `${typeName}Methods`;
  const lines = [
    JAVA_EDITABLE_SEAM_MARKER,
    JAVA_EDITABLE_SEAM_NOTE,
    `package ${packageName};`,
    "",
    `public final class ${helperName} {`,
    `  private ${helperName}() { }`,
    "",
  ];
  for (const method of type.methods) {
    const params = [
      `${typeName} self`,
      ...Object.entries(method.params).map(([name, paramType]) =>
        `${javaScalarType(paramType)} ${javaPropertyName(name)}`
      ),
    ].join(", ");
    lines.push(`  public static ${javaScalarType(method.returns)} ${javaMethodName(method.name)}(${params}) {`);
    lines.push(`    throw new UnsupportedOperationException("Implement ${typeName}.${javaMethodName(method.name)} in ${helperName}.");`);
    lines.push("  }");
    lines.push("");
  }
  lines.push("}");
  lines.push("");
  return { filename: `${helperName}.java`, source: lines.join("\n") };
}

function javaFieldType(field: FieldDecl, polymorphicTypeNames: Set<string>): string {
  switch (field.category.kind) {
    case "scalar":
      return field.enumName && !field.isOpenEnum ? javaEnumTypeName(field.enumName) : javaScalarType(field.category.scalarType);
    case "complex":
      return javaTypeName(field.category.typeName);
    case "collection_scalar":
      return `List<${field.enumName && !field.isOpenEnum ? javaEnumTypeName(field.enumName) : javaScalarType(field.category.scalarType)}>`;
    case "collection_complex":
      return `List<${javaTypeName(field.category.typeName)}>`;
    case "dict":
      return `Map<String, ${javaDictValueType(field.category.valueType)}>`;
  }
  void polymorphicTypeNames;
}

function javaScalarType(typeName: string): string {
  if (typeName.endsWith("[]")) {
    return `List<${javaScalarType(typeName.slice(0, -2))}>`;
  }
  if (typeName.endsWith("?")) {
    return javaScalarType(typeName.slice(0, -1));
  }
  if (typeName === "void") return "void";
  if (typeName === "Record<unknown>") return "Map<String, Object>";
  return JAVA_TYPE_MAP[typeName] ?? javaTypeName(typeName);
}

function javaDefault(field: FieldDecl, polymorphicTypeNames: Set<string>): string {
  if (
    field.hasExplicitDefault &&
    (field.category.kind === "collection_scalar" || field.category.kind === "collection_complex")
  ) {
    return " = new ArrayList<>()";
  }
  if (field.isOptional) {
    return " = null";
  }
  if (field.defaultValue !== null) {
    return ` = ${javaLiteral(field.defaultValue, field.enumName, scalarTypeOf(field))}`;
  }
  if (
    field.category.kind === "scalar" &&
    field.enumName &&
    !field.isOpenEnum &&
    field.allowedValues.length > 0
  ) {
    return ` = ${javaEnumTypeName(field.enumName)}.fromValue("${escapeJava(field.allowedValues[0])}")`;
  }
  switch (field.category.kind) {
    case "scalar":
      if (field.category.scalarType === "string") return ' = ""';
      if (field.category.scalarType === "boolean") return " = false";
      return ` = ${javaNumericLiteral(0, field.category.scalarType)}`;
    case "collection_scalar":
    case "collection_complex":
      return " = new ArrayList<>()";
    case "dict":
      return " = new LinkedHashMap<>()";
    case "complex":
      return " = null";
  }
  void polymorphicTypeNames;
}

function openEnumAliasParser(field: FieldDecl): string | null {
  if (field.enumName && field.isOpenEnum && hasParseAliases(field)) {
    return javaAliasParserName(field.enumName);
  }
  return null;
}

function javaDictValueType(valueType: string | undefined): string {
  if (!valueType || valueType === "unknown") return "Object";
  return JAVA_TYPE_MAP[valueType] ?? javaTypeName(valueType);
}

function javaDictValueLoad(valueExpr: string, valueType: string, contextExpr: string): string {
  if (JAVA_TYPE_MAP[valueType]) {
    return loadScalar(valueExpr, valueType, null);
  }
  return `${javaTypeName(valueType)}.load(${valueExpr}, ${contextExpr})`;
}

function loadScalar(valueExpr: string, scalarType: string, enumName: string | null, parseAliasFunction: string | null = null): string {
  if (enumName) {
    return `${javaEnumTypeName(enumName)}.fromValue(String.valueOf(${valueExpr}))`;
  }
  if (parseAliasFunction) {
    return `${parseAliasFunction}(String.valueOf(${valueExpr}))`;
  }
  switch (scalarType) {
    case "string":
      return `String.valueOf(${valueExpr})`;
    case "boolean":
      return `(${valueExpr} instanceof Boolean b ? b : Boolean.parseBoolean(String.valueOf(${valueExpr})))`;
    case "int32":
    case "integer":
      return `(${valueExpr} instanceof Number n ? n.intValue() : Integer.parseInt(String.valueOf(${valueExpr})))`;
    case "int64":
      return `(${valueExpr} instanceof Number n ? n.longValue() : Long.parseLong(String.valueOf(${valueExpr})))`;
    case "float32":
      return `(${valueExpr} instanceof Number n ? n.floatValue() : Float.parseFloat(String.valueOf(${valueExpr})))`;
    case "number":
    case "float":
    case "numeric":
    case "float64":
      return `(${valueExpr} instanceof Number n ? n.doubleValue() : Double.parseDouble(String.valueOf(${valueExpr})))`;
    default:
      return valueExpr;
  }
}

function coercionCheck(valueExpr: string, scalarType: string): string | null {
  switch (scalarType) {
    case "string":
      return `${valueExpr} instanceof String`;
    case "boolean":
      return `${valueExpr} instanceof Boolean`;
    case "int32":
    case "int64":
    case "integer":
      return `(${valueExpr} instanceof Integer || ${valueExpr} instanceof Long || ${valueExpr} instanceof Short || ${valueExpr} instanceof Byte)`;
    case "number":
    case "float":
    case "numeric":
    case "float32":
    case "float64":
      return `${valueExpr} instanceof Number`;
    default:
      return null;
  }
}

function coercionValue(assignment: CoercionAssignment, scalarType: string, field?: FieldDecl): string {
  if (assignment.isInput) {
    return loadScalar(
      "data",
      scalarType,
      field?.isOpenEnum ? null : field?.enumName ?? null,
      field ? openEnumAliasParser(field) : null,
    );
  }
  return javaLiteral(assignment.literalValue ?? "", field?.enumName ?? null, field ? scalarTypeOf(field) : null);
}

function javaLiteral(
  value: string | number | boolean,
  enumName: string | null,
  scalarType: string | null = null,
): string {
  if (typeof value === "string") {
    if (enumName) return `${javaEnumTypeName(enumName)}.fromValue("${escapeJava(value)}")`;
    return `"${escapeJava(value)}"`;
  }
  if (typeof value === "number" && scalarType) return javaNumericLiteral(value, scalarType);
  return String(value);
}

function scalarTypeOf(field: FieldDecl): string | null {
  return field.category.kind === "scalar" ? field.category.scalarType : null;
}

function javaNumericLiteral(value: number, scalarType: string): string {
  switch (scalarType) {
    case "int64":
      return `${value}L`;
    case "float32":
      return `${Number.isInteger(value) ? `${value}.0` : value}f`;
    case "number":
    case "float":
    case "numeric":
    case "float64":
      return `${Number.isInteger(value) ? `${value}.0` : value}d`;
    default:
      return String(value);
  }
}

function escapeJava(value: string): string {
  return value.replace(/\\/g, "\\\\").replace(/"/g, "\\\"").replace(/\r/g, "\\r").replace(/\n/g, "\\n");
}
