export function emitJavaFileContent(
  types: TypeDecl[],
  packageName: string,
  visitor: ExprVisitor,
  polymorphicTypeNames: Set<string>,
  enums: EnumDef[] = [],
  allTypes: TypeDecl[] = types,
  nativeSerialization: JavaNativeSerialization = "none",
): string {
  const lines: string[] = [];
  lines.push("// Code generated by Typra emitter; DO NOT EDIT.");
  lines.push(`package ${packageName};`);
  lines.push("");
  lines.push("import java.util.ArrayList;");
  lines.push("import java.util.LinkedHashMap;");
  lines.push("import java.util.List;");
  lines.push("import java.util.Map;");
  if (nativeSerialization === "jackson") {
    if (enums.length > 0) {
      lines.push("import com.fasterxml.jackson.annotation.JsonCreator;");
      lines.push("import com.fasterxml.jackson.annotation.JsonValue;");
    }
    lines.push("import com.fasterxml.jackson.annotation.JsonIgnore;");
    lines.push("import com.fasterxml.jackson.annotation.JsonInclude;");
    lines.push("import com.fasterxml.jackson.annotation.JsonProperty;");
    lines.push("import com.fasterxml.jackson.databind.annotation.JsonDeserialize;");
    lines.push("import com.fasterxml.jackson.databind.annotation.JsonSerialize;");
  }
  lines.push("");

  for (const enumDef of enums) emitEnum(enumDef, lines, false, nativeSerialization);
  for (const type of types) {
    emitType(type, lines, visitor, polymorphicTypeNames, allTypes, nativeSerialization);
  }

  return lines.join("\n");
}

export function emitJavaEnum(enumDef: EnumDef, packageName: string, nativeSerialization: JavaNativeSerialization = "none"): string {
  const lines = [
    "// Code generated by Typra emitter; DO NOT EDIT.",
    `package ${packageName};`,
    "",
  ];
  if (nativeSerialization === "jackson") {
    lines.push("import com.fasterxml.jackson.annotation.JsonCreator;");
    lines.push("import com.fasterxml.jackson.annotation.JsonValue;");
    lines.push("");
  }
  emitEnum(enumDef, lines, true, nativeSerialization);
  return lines.join("\n");
}

function emitEnum(enumDef: EnumDef, lines: string[], isPublic: boolean, nativeSerialization: JavaNativeSerialization = "none"): void {
  if (enumDef.isOpen) return;
  const enumName = javaEnumTypeName(enumDef.name);
  lines.push(`${isPublic ? "public " : ""}enum ${enumName} {`);
  for (const value of enumDef.values) {
    lines.push(`  ${javaEnumMemberName(value)}("${escapeJava(value)}"),`);
  }
  lines.push("  ;");
  lines.push("");
  if (nativeSerialization === "jackson") lines.push("  @JsonValue");
  lines.push("  public final String value;");
  lines.push(`  ${enumName}(String value) { this.value = value; }`);
  if (nativeSerialization === "jackson") lines.push("  @JsonCreator");
  lines.push(`  public static ${enumName} fromValue(String value) {`);
  if (hasParseAliases(enumDef)) {
    lines.push("    switch (value) {");
    for (const [canonical, aliases] of Object.entries(enumDef.parseAliases)) {
      for (const alias of aliases) {
        lines.push(`      case "${escapeJava(alias)}":`);
      }
      lines.push(`        return ${javaEnumMemberName(canonical)};`);
    }
    lines.push("      default:");
    lines.push("        break;");
    lines.push("    }");
  }
  lines.push(`    for (${enumName} item : values()) {`);
  lines.push("      if (item.value.equals(value)) return item;");
  lines.push("    }");
  lines.push("    return valueOf(value.toUpperCase().replace(\"-\", \"_\"));");
  lines.push("  }");
  lines.push("}");
  lines.push("");
}

function hasParseAliases(value: { parseAliases: Record<string, string[]> }): boolean {
  return Object.values(value.parseAliases).some(aliases => aliases.length > 0);
}

function javaAliasParserName(enumName: string): string {
  return `parse${javaEnumTypeName(enumName)}`;
}

function emitOpenEnumAliasParsers(fields: FieldDecl[], lines: string[]): void {
  const emitted = new Set<string>();
  for (const field of fields) {
    if (!field.enumName || !field.isOpenEnum || !hasParseAliases(field)) continue;
    if (emitted.has(field.enumName)) continue;
    emitted.add(field.enumName);
    lines.push(`  private static String ${javaAliasParserName(field.enumName)}(String value) {`);
    lines.push("    switch (value) {");
    for (const [canonical, aliases] of Object.entries(field.parseAliases)) {
      for (const alias of aliases) {
        lines.push(`      case "${escapeJava(alias)}":`);
      }
      lines.push(`        return "${escapeJava(canonical)}";`);
    }
    lines.push("      default:");
    lines.push("        return value;");
    lines.push("    }");
    lines.push("  }");
    lines.push("");
  }
}

function emitType(
  type: TypeDecl,
  lines: string[],
  visitor: ExprVisitor,
  polymorphicTypeNames: Set<string>,
  allTypes: TypeDecl[],
  nativeSerialization: JavaNativeSerialization,
): void {
  if (type.isProtocol) {
    emitProtocol(type, lines);
    return;
  }

  const typeName = javaTypeName(type.typeName.name);
  const modifiers = type.isAbstract ? "public abstract" : "public";
  const extendsClause = type.base ? ` extends ${javaTypeName(type.base.name)}` : "";
  if (nativeSerialization === "jackson") {
    lines.push(`@JsonSerialize(using = ${typeName}.TypraJacksonSerializer.class)`);
    lines.push(`@JsonDeserialize(using = ${typeName}.TypraJacksonDeserializer.class)`);
    lines.push("@JsonInclude(JsonInclude.Include.NON_NULL)");
  }
  lines.push(`${modifiers} class ${typeName}${extendsClause} {`);
  lines.push(`  public static final String SHORTHAND_PROPERTY = ${type.coercionProperty ? `"${type.coercionProperty}"` : "null"};`);
  lines.push("");

  const inheritedFields = collectInheritedFields(type, allTypes);
  for (const field of type.fields.filter(field => !inheritedFields.has(field.name))) {
    if (nativeSerialization === "jackson") {
      lines.push(`  @JsonProperty("${escapeJava(field.name)}")`);
      lines.push("  @JsonInclude(JsonInclude.Include.NON_NULL)");
    }
    lines.push(`  public ${javaFieldType(field, polymorphicTypeNames)} ${javaPropertyName(field.name)}${javaDefault(field, polymorphicTypeNames)};`);
  }
  if (retainsRawPayload(type)) {
    if (nativeSerialization === "jackson") lines.push("  @JsonIgnore");
    lines.push("  protected Map<String, Object> rawPayload;");
  }
  lines.push("");
  const inheritedDefaults = type.fields.filter(field =>
    inheritedFields.has(field.name) &&
    !field.isOptional &&
    field.defaultValue !== null
  );
  if (inheritedDefaults.length === 0) {
    lines.push(`  public ${typeName}() { }`);
  } else {
    lines.push(`  public ${typeName}() {`);
    for (const field of inheritedDefaults) {
      lines.push(`    this.${javaPropertyName(field.name)} = ${javaLiteral(field.defaultValue!, field.enumName, scalarTypeOf(field))};`);
    }
    lines.push("  }");
  }
  lines.push("");

  emitOpenEnumAliasParsers(type.fields, lines);
  emitLoad(type, lines, polymorphicTypeNames, inheritedFields);
  emitSave(type, lines, polymorphicTypeNames, inheritedFields);
  if (type.wire) {
    emitToWire(type.wire, lines);
  }

  function collectInheritedFields(type: TypeDecl, allTypes: TypeDecl[]): Set<string> {
    const fields = new Set<string>();
    let base = type.base ? allTypes.find(candidate => candidate.typeName.name === type.base?.name) : undefined;
    while (base) {
      for (const field of base.fields) fields.add(field.name);
      base = base.base ? allTypes.find(candidate => candidate.typeName.name === base?.base?.name) : undefined;
    }
    return fields;
  }

  emitSerializationHelpers(typeName, lines);
  if (nativeSerialization === "jackson") {
    emitJacksonHelpers(typeName, lines);
  }
  for (const factory of type.factories) {
    emitFactory(typeName, factory, visitor, lines);
  }
  for (const method of type.methods) {
    emitMethodDelegation(typeName, method, lines);
  }
  emitClassHelpers(lines);
  if (retainsRawPayload(type)) {
    emitRawPayloadHelpers(lines);
  }

  lines.push("}");
  lines.push("");
}

/**
 * An abstract base over an open discriminator has no wildcard subtype to absorb unrecognized
 * values, and Java emits `abstract class` for it, so those values need a concrete subclass to
 * land in. Without one, Java rejects a document every other target accepts: it conflates
 * "not directly instantiable" with "closed to unrecognized values", which are different
 * properties. C#, TypeScript and Python already emit the same carrier.
 */
function needsUnknownCarrier(type: TypeDecl): boolean {
  const dispatch = type.polymorphicDispatch;
  if (!dispatch || !type.isAbstract) {
    return false;
  }
  return !dispatch.defaultVariant && !isClosedPolymorphicDispatch(dispatch);
}

/**
 * Whether the type keeps the verbatim payload it was loaded from.
 *
 * A non-abstract base absorbs unrecognized values into itself and needs the payload to round-trip
 * undeclared keys. An abstract base delegates that to its carrier subclass, which stores the
 * payload on the inherited field, so the base must still declare it.
 */
function retainsRawPayload(type: TypeDecl): boolean {
  return type.polymorphicDispatch?.defaultVariant?.isSelfReference === true || needsUnknownCarrier(type);
}

function javaUnknownCarrierName(parentName: string): string {
  return `Unknown${javaTypeName(parentName)}`;
}

/**
 * Emit the concrete carrier for an abstract base whose discriminator is open.
 *
 * The base stays `abstract`, honouring the schema's `@abstract`, and unrecognized discriminator
 * values load as this subclass rather than throwing. Java allows one public top-level class per
 * file, so unlike the C# carrier this is emitted as its own compilation unit.
 *
 * The carrier declares no fields of its own: it stores the verbatim payload on the base's
 * `rawPayload` and lets the base's inherited `save` seed its result from it, so the unrecognized
 * discriminator value and every undeclared key survive a load/save round-trip unchanged.
 */
export function emitJavaUnknownCarrier(
  type: TypeDecl,
  packageName: string,
  nativeSerialization: JavaNativeSerialization = "none",
): { filename: string; source: string } | undefined {
  if (!needsUnknownCarrier(type)) {
    return undefined;
  }
  const parent = javaTypeName(type.typeName.name);
  const carrier = javaUnknownCarrierName(type.typeName.name);
  const lines: string[] = [
    "// Code generated by Typra emitter; DO NOT EDIT.",
    `package ${packageName};`,
    "",
    "import java.util.Map;",
    ...(nativeSerialization === "jackson" ? [
      "import com.fasterxml.jackson.databind.annotation.JsonDeserialize;",
      "import com.fasterxml.jackson.databind.annotation.JsonSerialize;",
      "",
    ] : [""]),
    "/**",
    ` * Carries a ${parent} whose discriminator value matches no known subtype.`,
    " * The unrecognized value stays on the discriminator field and every key the schema does not",
    ` * declare is preserved verbatim, so an unknown ${parent} survives a load/save round-trip`,
    " * unchanged.",
    " */",
    ...(nativeSerialization === "jackson" ? [
      `@JsonSerialize(using = ${carrier}.TypraJacksonSerializer.class)`,
      `@JsonDeserialize(using = ${carrier}.TypraJacksonDeserializer.class)`,
    ] : []),
    `public final class ${carrier} extends ${parent} {`,
    `  public ${carrier}() { }`,
    "",
    `  public static ${carrier} load(Object input, LoadContext context) {`,
    "    LoadContext ctx = context == null ? new LoadContext() : context;",
    "    Object data = ctx.processInput(input);",
    "    if (!(data instanceof Map<?, ?> map)) {",
    `      throw new IllegalArgumentException("Cannot load ${carrier} from a non-object value.");`,
    "    }",
    `    ${carrier} result = new ${carrier}();`,
    `    result.rawPayload = ${parent}.cloneRawMap(map);`,
  ];
  for (const assignment of type.load.assignments) {
    lines.push(`    result.rawPayload.remove("${escapeJava(assignment.sourceName)}");`);
  }
  lines.push(`    ${parent}.loadBaseInto(result, map, ctx);`);
  lines.push("    return ctx.processOutput(result);");
  lines.push("  }");
  if (nativeSerialization === "jackson") {
    lines.push("");
    emitJacksonHelpers(carrier, lines);
  }
  lines.push("}");
  lines.push("");
  return { filename: `${carrier}.java`, source: lines.join("\n") };
}

function emitJacksonHelpers(typeName: string, lines: string[]): void {
  lines.push(`  public static final class TypraJacksonSerializer extends com.fasterxml.jackson.databind.JsonSerializer<${typeName}> {`);
  lines.push("    @Override");
  lines.push(`    public void serialize(${typeName} value, com.fasterxml.jackson.core.JsonGenerator generator, com.fasterxml.jackson.databind.SerializerProvider serializers) throws java.io.IOException {`);
  lines.push("      generator.writeObject(value == null ? null : value.save(new SaveContext()));");
  lines.push("    }");
  lines.push("  }");
  lines.push("");
  lines.push(`  public static final class TypraJacksonDeserializer extends com.fasterxml.jackson.databind.JsonDeserializer<${typeName}> {`);
  lines.push("    @Override");
  lines.push(`    public ${typeName} deserialize(com.fasterxml.jackson.core.JsonParser parser, com.fasterxml.jackson.databind.DeserializationContext context) throws java.io.IOException {`);
  lines.push("      Object data = parser.getCodec().readValue(parser, Object.class);");
  lines.push(`      return ${typeName}.load(data, new LoadContext());`);
  lines.push("    }");
  lines.push("  }");
  lines.push("");
}

function emitProtocol(type: TypeDecl, lines: string[]): void {
  lines.push(`public interface ${javaTypeName(type.typeName.name)} {`);
  for (const method of type.methods) {
    const params = Object.entries(method.params).map(([name, typeName]) => `${javaScalarType(typeName)} ${javaPropertyName(name)}`).join(", ");
    lines.push(`  ${javaScalarType(method.returns)} ${javaMethodName(method.name)}(${params});`);
  }
  lines.push("}");
  lines.push("");
}

function emitLoad(
  type: TypeDecl,
  lines: string[],
  polymorphicTypeNames: Set<string>,
  inheritedFields: Set<string>,
): void {
  const typeName = javaTypeName(type.typeName.name);
  lines.push(`  @SuppressWarnings("unchecked")`);
  lines.push(`  public static ${typeName} load(Object input, LoadContext context) {`);
  lines.push("    LoadContext ctx = context == null ? new LoadContext() : context;");
  lines.push("    Object data = ctx.processInput(input);");
  emitCoercions(typeName, type.load.coercions, lines, type.fields, type.isAbstract);
  if (type.polymorphicDispatch) {
    emitPolymorphicDispatch(typeName, type.polymorphicDispatch, lines);
  }
  if (type.isAbstract) {
    const discriminator = type.polymorphicDispatch?.discriminatorField ?? "type";
    if (needsUnknownCarrier(type)) {
      lines.push("    if (data instanceof Map<?, ?>) {");
      lines.push(`      return ${javaUnknownCarrierName(type.typeName.name)}.load(data, ctx);`);
      lines.push("    }");
    }
    lines.push(`    throw new IllegalArgumentException("Cannot instantiate abstract ${typeName}; expected a matching '${escapeJava(discriminator)}' discriminator.");`);
    lines.push("  }");
    lines.push("");
    emitLoadBaseInto(type, lines, polymorphicTypeNames, inheritedFields);
    return;
  }
  lines.push("    if (!(data instanceof Map<?, ?> map)) {");
  lines.push(`      return ctx.processOutput(new ${typeName}());`);
  lines.push("    }");
  lines.push(`    ${typeName} result = new ${typeName}();`);
  if (type.polymorphicDispatch?.defaultVariant?.isSelfReference) {
    lines.push(`    if (map.get("${escapeJava(type.polymorphicDispatch.discriminatorField)}") instanceof String) {`);
    lines.push("      result.rawPayload = cloneRawMap(map);");
    for (const assignment of type.load.assignments) {
      lines.push(`      result.rawPayload.remove("${escapeJava(assignment.sourceName)}");`);
    }
    lines.push("    }");
  }
  lines.push(`    ${typeName}.loadBaseInto(result, map, ctx);`);
  lines.push("    return ctx.processOutput(result);");
  lines.push("  }");
  lines.push("");
  emitLoadBaseInto(type, lines, polymorphicTypeNames, inheritedFields);
}

function emitLoadBaseInto(
  type: TypeDecl,
  lines: string[],
  polymorphicTypeNames: Set<string>,
  inheritedFields: Set<string>,
): void {
  const typeName = javaTypeName(type.typeName.name);
  lines.push(`  static void loadBaseInto(${typeName} result, Map<?, ?> map, LoadContext ctx) {`);
  if (type.base) {
    lines.push(`    ${javaTypeName(type.base.name)}.loadBaseInto(result, map, ctx);`);
  }
  for (const assignment of type.load.assignments) {
    if (inheritedFields.has(assignment.fieldName)) continue;
    const field = type.fields.find(candidate => candidate.name === assignment.fieldName);
    const collectionHelper = type.collectionHelpers.find(helper =>
      helper.propertyName === assignment.fieldName && helper.hasNameProperty
    );
    if (shouldGuardMissingRequiredField(field)) {
      const wireName = escapeJava(assignment.sourceName);
      lines.push(`    if (!map.containsKey("${wireName}") || map.get("${wireName}") == null) {`);
      lines.push(`      throw new IllegalArgumentException(ctx.at("${wireName}").path + ": missing required field");`);
      lines.push("    }");
    }
    if (field) emitLoadField(field, collectionHelper, lines, polymorphicTypeNames);
  }
  lines.push("  }");
  lines.push("");
}

function emitCoercions(
  typeName: string,
  coercions: CoercionDecl[],
  lines: string[],
  fields: FieldDecl[] = [],
  isAbstract = false,
): void {
  assertDistinctNumericCoercionFamilies(typeName, coercions);
  let emittedBroadNumberGuard = false;
  const orderedCoercions = [...coercions].sort(
    (left, right) => numericCoercionRank(left.scalarType) - numericCoercionRank(right.scalarType),
  );
  for (const coercion of orderedCoercions) {
    if (isBroadNumberCoercion(coercion.scalarType)) {
      if (emittedBroadNumberGuard) continue;
      emittedBroadNumberGuard = true;
    }
    const check = coercionCheck("data", coercion.scalarType);
    if (!check) continue;
    lines.push(`    if (${check}) {`);
    if (isAbstract) {
      lines.push("      Map<String, Object> coerced = new LinkedHashMap<>();");
      for (const assignment of coercion.assignments) {
        const field = fields.find(candidate => candidate.name === assignment.fieldName);
        lines.push(`      coerced.put("${escapeJava(assignment.fieldName)}", ${coercionValue(assignment, coercion.scalarType, field)});`);
      }
      lines.push(`      return ${typeName}.load(coerced, ctx);`);
      lines.push("    }");
      continue;
    }
    lines.push(`      ${typeName} result = new ${typeName}();`);
    for (const assignment of coercion.assignments) {
      const field = fields.find(candidate => candidate.name === assignment.fieldName);
      lines.push(`      result.${javaPropertyName(assignment.fieldName)} = ${coercionValue(assignment, coercion.scalarType, field)};`);
    }
    lines.push("      return ctx.processOutput(result);");
    lines.push("    }");
  }
}

function assertDistinctNumericCoercionFamilies(typeName: string, coercions: CoercionDecl[]): void {
  for (const [family, matches] of [
    ["integral", coercions.filter(coercion => isIntegralCoercion(coercion.scalarType))],
    ["floating-point", coercions.filter(coercion => isBroadNumberCoercion(coercion.scalarType))],
  ] as const) {
    if (matches.length > 1) {
      throw new Error(
        `Java emitter cannot distinguish multiple ${family} coercions for ${typeName}: ${matches.map(match => match.scalarType).join(", ")}`,
      );
    }
  }
}

function numericCoercionRank(scalarType: string): number {
  if (isIntegralCoercion(scalarType)) return 1;
  if (isBroadNumberCoercion(scalarType)) return 2;
  return 0;
}

function isIntegralCoercion(scalarType: string): boolean {
  return scalarType === "int32" || scalarType === "int64" || scalarType === "integer";
}

function isBroadNumberCoercion(scalarType: string): boolean {
  return scalarType === "number"
    || scalarType === "float"
    || scalarType === "numeric"
    || scalarType === "float32"
    || scalarType === "float64";
}

function emitPolymorphicDispatch(typeName: string, dispatch: PolymorphicDispatchDecl, lines: string[]): void {
  const isClosed = isClosedPolymorphicDispatch(dispatch);
  lines.push("    if (data instanceof Map<?, ?> dispatchMap) {");
  lines.push(`      Object discriminator = dispatchMap.get("${escapeJava(dispatch.discriminatorField)}");`);
  lines.push("      if (!(discriminator instanceof String discriminatorString) || discriminatorString.isEmpty()) {");
  lines.push(`        throw new IllegalArgumentException("Invalid ${typeName} discriminator field '${escapeJava(dispatch.discriminatorField)}': expected non-blank string");`);
  lines.push("      }");
  lines.push("      switch (discriminatorString) {");
  for (const variant of dispatch.variants) {
    lines.push(`        case "${escapeJava(variant.value)}":`);
    lines.push(`          return ${javaTypeName(variant.typeName.name)}.load(data, ctx);`);
  }
  lines.push("        default:");
  if (dispatch.defaultVariant && !dispatch.defaultVariant.isSelfReference) {
    lines.push(`          return ${javaTypeName(dispatch.defaultVariant.typeName.name)}.load(data, ctx);`);
  } else if (isClosed) {
    lines.push(`          throw new IllegalArgumentException("Unknown ${typeName} discriminator field '${escapeJava(dispatch.discriminatorField)}' value: " + discriminatorString);`);
  } else {
    lines.push("          break;");
  }
  lines.push("      }");
  lines.push("    }");
  void typeName;
}

function emitLoadField(
  field: FieldDecl,
  collectionHelper: CollectionHelperDecl | undefined,
  lines: string[],
  polymorphicTypeNames: Set<string>,
): void {
  const wireName = escapeJava(field.name);
  const name = javaPropertyName(field.name);
  lines.push(`    if (map.containsKey("${wireName}") && map.get("${wireName}") != null) {`);
  switch (field.category.kind) {
    case "scalar":
      lines.push(`      result.${name} = ${loadScalar(`map.get("${wireName}")`, field.category.scalarType, field.isOpenEnum ? null : field.enumName, openEnumAliasParser(field))};`);
      break;
    case "complex":
      lines.push(`      result.${name} = ${javaTypeName(field.category.typeName)}.load(map.get("${wireName}"), ctx.at("${wireName}"));`);
      break;
    case "collection_scalar":
      lines.push(`      result.${name} = new ArrayList<>();`);
      lines.push(`      if (map.get("${wireName}") instanceof Iterable<?> values) {`);
      lines.push("        for (Object item : values) {");
      lines.push(`                      result.${name}.add(${loadScalar("item", field.category.scalarType, field.isOpenEnum ? null : field.enumName, openEnumAliasParser(field))});`);
      lines.push("        }");
      lines.push("      }");
      break;
    case "collection_complex":
      lines.push(`      result.${name} = new ArrayList<>();`);
      if (collectionHelper?.hasNameProperty) {
        lines.push(`      if (map.get("${wireName}") instanceof Map<?, ?> values) {`);
        lines.push("        for (Map.Entry<?, ?> entry : values.entrySet()) {");
        lines.push("          if (entry.getValue() instanceof Iterable<?>) {");
        lines.push(`            throw new IllegalArgumentException(ctx.at("${wireName}").at(String.valueOf(entry.getKey())).path + ": invalid named collection entry category array");`);
        lines.push("          }");
        lines.push("          Map<String, Object> itemData;");
        lines.push("          if (entry.getValue() instanceof Map<?, ?> itemMap) {");
        lines.push("            itemData = copyMap(itemMap);");
        lines.push("          } else {");
        lines.push("            itemData = new LinkedHashMap<>();");
        lines.push(...emitJavaEntryShorthandArms(collectionHelper, "            "));
        lines.push("          }");
        lines.push("          itemData.put(\"name\", String.valueOf(entry.getKey()));");
        lines.push(`          ${javaTypeName(field.category.typeName)} item = ${javaTypeName(field.category.typeName)}.load(itemData, ctx.at("${wireName}").at(String.valueOf(entry.getKey())));`);
        lines.push(`          result.${name}.add(item);`);
        lines.push("        }");
        lines.push(`      } else if (map.get("${wireName}") instanceof Iterable<?> values) {`);
      } else {
        lines.push(`      if (map.get("${wireName}") instanceof Iterable<?> values) {`);
      }
      lines.push(`        int ${name}Index = 0;`);
      lines.push("        for (Object item : values) {");
      lines.push(`          result.${name}.add(${javaTypeName(field.category.typeName)}.load(item, ctx.at("${wireName}").atIndex(${name}Index++)));`);
      lines.push("        }");
      lines.push("      }");
      break;
    case "dict":
      lines.push(`      if (map.get("${wireName}") instanceof Map<?, ?> dict) {`);
      if (!field.category.valueType || field.category.valueType === "unknown") {
        lines.push(`        result.${name} = copyMap(dict);`);
      } else {
        lines.push(`        result.${name} = new LinkedHashMap<>();`);
        lines.push("        for (Map.Entry<?, ?> entry : dict.entrySet()) {");
        lines.push(`          result.${name}.put(String.valueOf(entry.getKey()), ${javaDictValueLoad("entry.getValue()", field.category.valueType, `ctx.at("${wireName}").at(String.valueOf(entry.getKey()))`)});`);
        lines.push("        }");
      }
      lines.push("      }");
      break;
  }
  lines.push("    }");
  void polymorphicTypeNames;
}

