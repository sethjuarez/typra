/**
 * Expand an immediate scalar entry of a name-keyed collection.
 *
 * Without a declaration this keeps the historical positional behaviour, which is
 * unsound for a discriminated element type because its first declared field is
 * the discriminator. With `@entryShorthand` the value lands in the declared
 * field and the constants come from the element's own `@coerce` table.
 */
function emitJavaEntryShorthandArms(helper: CollectionHelperDecl, indent: string): string[] {
  const target = entryShorthandTarget(helper, "kind");
  const shorthand = helper.entryShorthand;
  const cases = shorthand ? orderedEntryShorthandCases(shorthand.cases) : [];

  if (!shorthand || cases.length === 0) {
    return [`${indent}itemData.put("${target}", entry.getValue());`];
  }

  const lines: string[] = [`${indent}Object shorthandValue = entry.getValue();`];
  let first = true;
  for (const entryCase of cases) {
    const check = javaScalarValueCheck(entryCase.scalarType);
    if (!check) continue;
    lines.push(`${indent}${first ? "if" : "} else if"} (${check}) {`);
    first = false;
    for (const a of entryCase.assignments) {
      lines.push(`${indent}  itemData.put("${a.fieldName}", ${javaShorthandLiteral(a.literalValue)});`);
    }
  }
  if (!first) lines.push(`${indent}}`);
  lines.push(`${indent}itemData.put("${shorthand.valueField}", shorthandValue);`);
  return lines;
}

/** Java `instanceof` test recognising a decoded value of the given TypeSpec scalar. */
function javaScalarValueCheck(scalarType: string): string | null {
  if (isIntegralScalar(scalarType)) {
    return "shorthandValue instanceof Integer || shorthandValue instanceof Long"
      + " || shorthandValue instanceof Short || shorthandValue instanceof Byte";
  }
  if (isFractionalScalar(scalarType)) {
    return "shorthandValue instanceof Double || shorthandValue instanceof Float"
      + " || shorthandValue instanceof java.math.BigDecimal";
  }
  if (isStringEncodedScalar(scalarType)) return "shorthandValue instanceof String";
  if (isBooleanScalar(scalarType)) return "shorthandValue instanceof Boolean";
  return null;
}

/** Render a coercion constant as a Java literal, preserving its declared JSON type. */
function javaShorthandLiteral(value: string | number | boolean | null): string {
  if (value === null) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return String(value);
  return JSON.stringify(value);
}

function emitSave(
  type: TypeDecl,
  lines: string[],
  polymorphicTypeNames: Set<string>,
  inheritedFields: Set<string>,
): void {
  lines.push("  public Map<String, Object> save(SaveContext context) {");
  lines.push("    SaveContext ctx = context == null ? new SaveContext() : context;");
  lines.push(`    ${javaTypeName(type.typeName.name)} obj = ctx.processObject(this);`);
  if (retainsRawPayload(type)) {
    lines.push("    Map<String, Object> result = obj.rawPayload == null ? new LinkedHashMap<>() : cloneRawMap(obj.rawPayload);");
  } else {
    lines.push("    Map<String, Object> result = new LinkedHashMap<>();");
  }
  lines.push("    obj.saveFields(result, ctx);");
  lines.push("    return ctx.processDict(result);");
  lines.push("  }");
  lines.push("");
  lines.push("  protected void saveFields(Map<String, Object> result, SaveContext ctx) {");
  if (type.base) lines.push("    super.saveFields(result, ctx);");
  lines.push(`    ${javaTypeName(type.typeName.name)} obj = this;`);
  for (const field of type.save.assignments) {
    if (inheritedFields.has(field.fieldName)) continue;
    const collectionHelper = type.collectionHelpers.find(helper =>
      helper.propertyName === field.fieldName && helper.hasNameProperty
    );
    emitSaveField(
      field,
      collectionHelper,
      lines,
      polymorphicTypeNames,
    );
  }
  lines.push("  }");
  lines.push("");
}

function emitSaveField(
  field: SaveAssignment,
  collectionHelper: CollectionHelperDecl | undefined,
  lines: string[],
  polymorphicTypeNames: Set<string>,
): void {
  const name = field.fieldName;
  const category = field.category;
  const enumName = field.isOpenEnum ? null : field.enumName;
  const wireName = escapeJava(name);
  const propertyName = javaPropertyName(name);
  switch (category.kind) {
    case "scalar":
      if (shouldOmitAbsentOnSave(field, "always-check")) {
        lines.push(`    if (obj.${propertyName} != null) result.put("${wireName}", ${enumName ? `obj.${propertyName}.value` : `serializeScalar(obj.${propertyName})`});`);
      } else {
        lines.push(`    result.put("${wireName}", ${enumName ? `obj.${propertyName}.value` : `serializeScalar(obj.${propertyName})`});`);
      }
      break;
    case "dict":
      if (category.valueType && category.valueType !== "unknown" && !JAVA_TYPE_MAP[category.valueType]) {
        if (shouldOmitAbsentOnSave(field, "always-check")) lines.push(`    if (obj.${propertyName} != null) {`);
        lines.push("      Map<String, Object> items = new LinkedHashMap<>();");
        lines.push(`      for (Map.Entry<String, ${javaDictValueType(category.valueType)}> entry : obj.${propertyName}.entrySet()) items.put(entry.getKey(), entry.getValue().save(ctx));`);
        lines.push(`      result.put("${wireName}", items);`);
        if (shouldOmitAbsentOnSave(field, "always-check")) lines.push("    }");
      } else {
        if (shouldOmitAbsentOnSave(field, "always-check")) {
          lines.push(`    if (obj.${propertyName} != null) result.put("${wireName}", serializeScalar(obj.${propertyName}));`);
        } else {
          lines.push(`    result.put("${wireName}", serializeScalar(obj.${propertyName}));`);
        }
      }
      break;
    case "complex":
      if (shouldOmitAbsentOnSave(field, "always-check")) {
        lines.push(`    if (obj.${propertyName} != null) result.put("${wireName}", obj.${propertyName}.save(ctx));`);
      } else {
        lines.push(`    result.put("${wireName}", obj.${propertyName}.save(ctx));`);
      }
      break;
    case "collection_scalar":
      if (enumName) {
        if (shouldOmitAbsentOnSave(field, "always-check")) lines.push(`    if (obj.${propertyName} != null) {`);
        lines.push("      List<Object> items = new ArrayList<>();");
        lines.push(`      for (${javaEnumTypeName(enumName)} item : obj.${propertyName}) items.add(item.value);`);
        lines.push(`      result.put("${wireName}", items);`);
        if (shouldOmitAbsentOnSave(field, "always-check")) lines.push("    }");
      } else {
        if (shouldOmitAbsentOnSave(field, "always-check")) {
          lines.push(`    if (obj.${propertyName} != null) result.put("${wireName}", new ArrayList<>(obj.${propertyName}));`);
        } else {
          lines.push(`    result.put("${wireName}", new ArrayList<>(obj.${propertyName}));`);
        }
      }
      break;
    case "collection_complex":
      if (shouldOmitAbsentOnSave(field, "always-check")) lines.push(`    if (obj.${propertyName} != null) {`);
      if (collectionHelper?.hasNameProperty) {
        lines.push("      List<Object> serializedItems = new ArrayList<>();");
        lines.push("      List<String> itemNames = new ArrayList<>();");
        lines.push("      java.util.Set<String> names = new java.util.HashSet<>();");
        lines.push("      boolean canUseObject = true;");
        lines.push(`      for (${javaTypeName(category.typeName)} item : obj.${propertyName}) {`);
        lines.push("        String itemName = item.name;");
        lines.push("        itemNames.add(itemName);");
        lines.push("        if (itemName == null || itemName.isEmpty() || !names.add(itemName)) canUseObject = false;");
        lines.push("        Map<String, Object> itemData = new LinkedHashMap<>(item.save(ctx));");
        lines.push('        if ("".equals(itemData.get("name"))) itemData.remove("name");');
        lines.push("        serializedItems.add(itemData);");
        lines.push("      }");
        lines.push(`      if ("array".equals(ctx.collectionFormat) || !canUseObject) {`);
        lines.push(`        result.put("${wireName}", serializedItems);`);
        lines.push("      } else {");
        lines.push("        Map<String, Object> objectItems = new LinkedHashMap<>();");
        lines.push("        for (int index = 0; index < serializedItems.size(); index++) {");
        lines.push("          Map<String, Object> itemData = new LinkedHashMap<>((Map<String, Object>) serializedItems.get(index));");
        lines.push("          String itemName = itemNames.get(index);");
        lines.push('          itemData.remove("name");');
        lines.push(`          if (ctx.useShorthand && ${javaTypeName(category.typeName)}.SHORTHAND_PROPERTY != null && itemData.size() == 1 && itemData.containsKey(${javaTypeName(category.typeName)}.SHORTHAND_PROPERTY)) {`);
        lines.push(`            objectItems.put(itemName, itemData.get(${javaTypeName(category.typeName)}.SHORTHAND_PROPERTY));`);
        lines.push("          } else {");
        lines.push("            objectItems.put(itemName, itemData);");
        lines.push("          }");
        lines.push("        }");
        lines.push(`        result.put("${wireName}", objectItems);`);
        lines.push("      }");
      } else {
        lines.push("      List<Object> items = new ArrayList<>();");
        lines.push(`      for (${javaTypeName(category.typeName)} item : obj.${propertyName}) items.add(item.save(ctx));`);
        lines.push(`      result.put("${wireName}", items);`);
      }
      if (shouldOmitAbsentOnSave(field, "always-check")) lines.push("    }");
      break;
  }
  void polymorphicTypeNames;
}

function emitClassHelpers(lines: string[]): void {
  lines.push("  private static Map<String, Object> copyMap(Map<?, ?> source) {");
  lines.push("    Map<String, Object> result = new LinkedHashMap<>();");
  lines.push("    for (Map.Entry<?, ?> entry : source.entrySet()) {");
  lines.push("      result.put(String.valueOf(entry.getKey()), entry.getValue());");
  lines.push("    }");
  lines.push("    return result;");
  lines.push("  }");
  lines.push("");
  lines.push("  private static Object serializeScalar(Object value) {");
  lines.push("    if (value instanceof Enum<?> e) return e.name().toLowerCase().replace(\"_\", \"-\");");
  lines.push("    return value;");
  lines.push("  }");
  lines.push("");
}

/**
 * Visibility is uniform across every class that retains a raw payload. Java forbids hiding an
 * inherited static method with weaker access, so a `private static` helper on a subclass of a
 * base that exposes the same helper more widely would not compile. C# emits `protected static`
 * for the same reason.
 */
function emitRawPayloadHelpers(lines: string[]): void {
  lines.push("  protected static Map<String, Object> cloneRawMap(Map<?, ?> source) {");
  lines.push("    Map<String, Object> result = new LinkedHashMap<>();");
  lines.push("    for (Map.Entry<?, ?> entry : source.entrySet()) {");
  lines.push("      result.put(String.valueOf(entry.getKey()), cloneRawValue(entry.getValue()));");
  lines.push("    }");
  lines.push("    return result;");
  lines.push("  }");
  lines.push("");
  lines.push("  protected static Object cloneRawValue(Object value) {");
  lines.push("    if (value instanceof Map<?, ?> map) return cloneRawMap(map);");
  lines.push("    if (value instanceof Iterable<?> values) {");
  lines.push("      List<Object> result = new ArrayList<>();");
  lines.push("      for (Object item : values) result.add(cloneRawValue(item));");
  lines.push("      return result;");
  lines.push("    }");
  lines.push("    return value;");
  lines.push("  }");
  lines.push("");
}

/**
 * A wire field is emitted only when the requested provider actually maps it, matching every other
 * backend (Go: `if wireName, ok := mapping[provider]`). Defaulting to the schema field name leaks
 * fields into payloads for providers — or for an empty/null provider — that never declared them.
 */
function emitToWire(wire: WireDecl, lines: string[]): void {
  lines.push("  public Map<String, Object> toWire(String provider) {");
  lines.push("    Map<String, Object> result = new LinkedHashMap<>();");
  lines.push("    String target = provider == null ? \"\" : provider;");
  for (const field of wire.mappings) {
    lines.push("    {");
    lines.push(`      String wireName = null;`);
    for (const [provider, name] of Object.entries(field.wireNames)) {
      lines.push(`      if (target.equals("${escapeJava(provider)}")) { wireName = "${escapeJava(name)}"; }`);
    }
    lines.push(`      if (wireName != null && this.${javaPropertyName(field.fieldName)} != null) result.put(wireName, serializeScalar(this.${javaPropertyName(field.fieldName)}));`);
    lines.push("    }");
  }
  lines.push("    return result;");
  lines.push("  }");
  lines.push("");
}

